export type VocabularyGroup = {
  id: string;
  label: string;
  items: string[];
};

export type WordPack = {
  id: string;
  seriesId: string;
  name: string;
  vocabulary: string[];
  vocabularyGroups: VocabularyGroup[];
  patterns: string[];
};

export type WordPackSeries = {
  id: string;
  name: string;
  status: "available" | "awaiting-words";
  packCount?: number;
};

