const makePack = (
  id: string,
  seriesId: string,
  name: string,
  vocabularyGroups: VocabularyGroup[],
  patterns: string[],
): WordPack => ({
  id,
  seriesId,
  name,
  vocabularyGroups,
  vocabulary: vocabularyGroups.flatMap((group) => group.items),
  patterns,
});

